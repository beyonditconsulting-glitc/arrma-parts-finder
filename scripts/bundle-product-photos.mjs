import {
  mkdirSync,
  readFileSync,
  writeFileSync,
  existsSync,
  renameSync,
  rmSync,
} from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { spawn } from "node:child_process";
import { parts } from "../src/catalog.ts";
import { productPhoto } from "../src/productPhotos.ts";
const root = new URL("../", import.meta.url);
const receiptUrl = new URL(
  "database/discovery/bundled-product-photos.json",
  root,
);
const previous = existsSync(receiptUrl)
  ? JSON.parse(readFileSync(receiptUrl, "utf8")).photos
  : [];
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");
mkdirSync(new URL("assets/products/", root), { recursive: true });
const photos = [];
for (const part of parts) {
  const photo = productPhoto(part);
  if (!photo || photo.publisher !== "Jenny’s RC") continue;
  const url = new URL(photo.url);
  if (
    url.protocol !== "https:" ||
    url.hostname !== "cdn.shopify.com" ||
    url.username ||
    url.password ||
    !/^[A-Za-z0-9_-]+$/.test(part.id)
  )
    throw Error("Unexpected photo identity/source");
  const extension = url.pathname.match(/\.(jpe?g|png)$/i)?.[0].toLowerCase();
  if (!extension)
    throw Error(`Unsupported original photo format for ${part.id}`);
  const relativePath = `assets/products/jennys-${part.id}${extension}`;
  const path = fileURLToPath(new URL(relativePath, root));
  const prior = previous.find(
    (p) => p.catalogPartId === part.id && p.sourceImageUrl === photo.url,
  );
  let capturedAt = prior?.capturedAt;
  if (
    process.argv.includes("--refresh") ||
    !prior ||
    !existsSync(path) ||
    digest(readFileSync(path)) !== prior.assetSha256
  ) {
    const temporary = path + ".download";
    try {
      await new Promise((resolve, reject) => {
        const child = spawn(
          "curl",
          [
            "--fail",
            "--silent",
            "--show-error",
            "--location",
            "--max-time",
            "45",
            "--output",
            temporary,
            photo.url,
          ],
          { stdio: ["ignore", "ignore", "pipe"] },
        );
        let error = "";
        child.stderr.on("data", (chunk) => {
          error += chunk.toString();
        });
        child.on("error", reject);
        child.on("close", (code) =>
          code === 0
            ? resolve()
            : reject(
                Error(`Photo download failed for ${part.id}: ${error.trim()}`),
              ),
        );
      });
      const bytes = readFileSync(temporary);
      const jpeg = bytes[0] === 0xff && bytes[1] === 0xd8 && bytes[2] === 0xff;
      const png = bytes
        .subarray(0, 8)
        .equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]));
      if (!jpeg && !png)
        throw Error(`Not a supported image response for ${part.id}`);
      renameSync(temporary, path);
      capturedAt = new Date().toISOString();
    } finally {
      rmSync(temporary, { force: true });
    }
  }
  const bytes = readFileSync(path);
  photos.push({
    catalogPartId: part.id,
    manufacturerPartNumber: part.manufacturerPartNumber,
    publisher: photo.publisher,
    sourceImageUrl: photo.url,
    sourceProductUrl: photo.sourceUrl,
    sourceSha256: photo.sourceSha256,
    relativePath,
    assetSha256: digest(bytes),
    byteCount: bytes.length,
    capturedAt,
  });
}
if (!photos.length) throw Error("No exact photo assets available");
writeFileSync(
  receiptUrl,
  JSON.stringify(
    {
      scope:
        "Unmodified original images tied to exact Jenny product matches. No borrowed photos for unresolved parts.",
      photos,
    },
    null,
    2,
  ) + "\n",
);
const entries = photos
  .map(
    (p) =>
      `  ${JSON.stringify(p.catalogPartId)}: { url: ${JSON.stringify(p.sourceImageUrl)}, source: require(${JSON.stringify("../" + p.relativePath)}) },`,
  )
  .join("\n");
writeFileSync(
  new URL("src/productPhotoAssets.ts", root),
  `// Generated by scripts/bundle-product-photos.mjs; URLs guard against stale image mappings.\nimport type { ImageSourcePropType } from 'react-native';\nconst assets: Record<string,{url:string;source:ImageSourcePropType}> = {\n${entries}\n};\nexport function bundledProductPhoto(partId:string,url:string) {\n const asset=assets[partId];return asset?.url===url ? asset.source : undefined;\n}\n`,
);
console.log(
  `Bundled ${photos.length} exact product photos (${photos.reduce((n, p) => n + p.byteCount, 0)} bytes); no retailer connection needed to serve these assets.`,
);
